"""«Матрица» — пейзаж, собранный светодиодной сеткой.

Почему не дитеринг. Матрица Байера решает на каждую клетку «да/нет», и на
больших площадях её порядок виден как перекрёстная штриховка — картинка
читается вязаным полотном. Здесь другое: сетка регулярная, а яркость у
каждой ячейки своя, непрерывная. Градиент получается гладким, потому что
он и есть гладкий, а не набран плотностью точек.

Почему квадраты, а не круги. Круглая точка — чужой почерк. У нас вся
графика собрана из квадратной клетки с жёстким краем, и матрица должна
быть из неё же. Зазор между ячейками при этом обязателен: без него сетка
исчезает и остаётся обычная растровая картинка.

Рельеф под сеткой не нарисован, а посчитан: многооктавный шум по решётке
со сглаживанием, из него нормаль, из нормали — свет. Отсюда и объём.
"""
import math, os
from PIL import Image, ImageDraw

OUT = '/tmp/claude-1000/-home-mista--------/c81872d7-c4ff-4b62-998d-763257e21816/scratchpad/art'
INK   = (14, 15, 17)
PLATE = (237, 239, 241)
BLUE  = (42, 99, 255)
BLUEL = (76, 124, 255)

def lattice(ix, iy, seed):
    h = (ix*374761393 + iy*668265263 + seed*2246822519) & 0xFFFFFFFF
    h = ((h ^ (h >> 13)) * 1274126177) & 0xFFFFFFFF
    h ^= h >> 16
    return (h & 0xFFFF) / 0xFFFF

def smooth(t):
    # Кубическое сглаживание: без него между узлами решётки видны изломы,
    # и «гладкое поле» перестаёт быть гладким.
    return t*t*(3 - 2*t)

def value_noise(x, y, seed):
    ix, iy = math.floor(x), math.floor(y)
    fx, fy = smooth(x-ix), smooth(y-iy)
    a = lattice(ix,   iy,   seed)
    b = lattice(ix+1, iy,   seed)
    c = lattice(ix,   iy+1, seed)
    d = lattice(ix+1, iy+1, seed)
    return (a*(1-fx) + b*fx)*(1-fy) + (c*(1-fx) + d*fx)*fy

def fbm(x, y, seed, octaves=4, falloff=0.42):
    """Октав мало и затухают быстро.

    Много октав дают мелкую рябь по всему кадру: технически это рельеф, а
    визуально гравий. Крупная форма важнее детализации — деталь тут и так
    даёт сама сетка.
    """
    v, amp, norm, f = 0.0, 1.0, 0.0, 1.0
    for o in range(octaves):
        v += value_noise(x*f, y*f, seed+o) * amp
        norm += amp
        amp *= falloff
        f *= 2.0
    return v / norm

def build(W, H, cell, gap, name, seed=7, tilt=0.55, accent=0.0, dark=True,
          dim=1.0, icon_zone=None):
    """dim — общая яркость, icon_zone — (верх, низ) в долях высоты.

    Домашний экран отличается от экрана блокировки только яркостью.
    Композиция, зерно, наклон и сид те же самые, и это важнее, чем может
    показаться: при разблокировке одна картинка перетекает в другую, и
    если формы не совпадают, переход читается как подмена обоев. Гасим
    свет, а не меняем сцену.

    icon_zone гасит дополнительно ту полосу, где стоят иконки. Ровное
    затемнение по всему кадру пришлось бы делать таким сильным, что от
    картинки ничего не осталось бы: иконки лежат в середине, а гребень
    проходит как раз через неё.
    """
    bg = INK if dark else PLATE
    lamp = (255, 255, 255) if dark else (14, 15, 17)
    acc = BLUEL if dark else BLUE
    img = Image.new('RGB', (W, H), bg)
    d = ImageDraw.Draw(img)
    cols, rows = W//cell, H//cell

    # Частота разная по осям, и в этом всё дело. При одинаковой шум даёт
    # кляксы: технически рельеф, визуально дым. Растянутый вдоль одной оси
    # превращается в гряды — длинные формы с гребнем, по которому и
    # скользит свет.
    freq_along  = 0.85 / cols     # вдоль гряды — редко
    freq_across = 3.1 / cols      # поперёк — часто

    def height(cx, cy):
        # Сдвиг разворачивает гряды по диагонали.
        return fbm(cx*freq_along, (cy - cx*tilt)*freq_across, seed)

    dots = []
    for cy in range(rows):
        for cx in range(cols):
            h0 = height(cx, cy)
            # Нормаль по разности высот — отсюда берётся свет.
            hx = height(cx+1, cy) - height(cx-1, cy)
            hy = height(cx, cy+1) - height(cx, cy-1)
            # Свет сверху-слева: гребень, обращённый к нему, вспыхивает,
            # обратный склон уходит в чёрный.
            # Свет скользящий, почти вдоль поверхности: он вытягивает
            # гребни в длинные светлые полосы и роняет всё остальное в
            # тень. Свет «сверху» дал бы ровную серую заливку.
            # Свет поперёк гряд: главную работу делает hy, потому что
            # именно поперёк рельеф и меняется.
            lit = (-hx*0.25 - hy*1.0) * 26.0 + 0.30
            lit += (h0 - 0.5) * 0.45

            # Маска кадра: свет приходит из одного угла и гаснет к
            # противоположному. Без неё матрица заполняет холст равномерно,
            # и чёрного — того, что и держит такую картинку — не остаётся.
            u, v = cx/max(1, cols-1), cy/max(1, rows-1)
            reach = (u*0.45 + (1-v)*0.55)
            lit *= max(0.0, 1.25 - reach*1.25) ** 1.1
            dots.append((cx, cy, lit))

    # Нормировка по факту, а не по догадке: у шума нет гарантированного
    # диапазона, и жёсткие пороги дали бы то пересвет, то мёртвый кадр.
    vals = sorted(v for _, _, v in dots)
    lo = vals[int(len(vals)*0.34)]
    hi = vals[int(len(vals)*0.995)]
    rng = max(1e-6, hi - lo)

    for cx, cy, lit in dots:
        t = (lit - lo) / rng
        t = max(0.0, min(1.0, t)) ** 1.15
        # Доля синего берётся от яркости ДО гашения и запоминается.
        # Считать её после — значит вычитать порог из уже приглушённого
        # значения: разность уходит в минус, и смесь экстраполируется в
        # противоположную от синего сторону. Акцент становился жёлтым.
        is_accent = accent > 0 and t > accent
        accent_k = ((t - accent) / max(1e-6, 1 - accent)) if is_accent else 0.0
        if icon_zone is not None:
            top, bot = icon_zone
            v = cy / max(1, rows-1)
            if top <= v <= bot:
                t *= 0.42
            else:
                # За пределами полосы гашение смягчается, иначе виден
                # резкий край — полоса читалась бы прямоугольником.
                edge = min(abs(v-top), abs(v-bot))
                t *= 0.42 + min(1.0, edge/0.10) * 0.58
        # Акцент гасится слабее остальных: при равном гашении синий уходит
        # первым — его и так мало, — и домашний экран теряет единственную
        # приметную деталь. Форма от этого не меняется, а подпись остаётся.
        t *= dim ** (0.45 if is_accent else 1.0)
        if t < 0.015:
            continue
        base = lamp
        if is_accent:
            # Единственный цвет во всей системе — и он достаётся только
            # самым ярким гребням, иначе перестаёт быть акцентом.
            mixk = min(1.0, accent_k * 1.3)
            base = tuple(int(lamp[i] + (acc[i]-lamp[i])*mixk) for i in range(3))
        color = tuple(int(bg[i] + (base[i]-bg[i])*t) for i in range(3))
        x0, y0 = cx*cell, cy*cell
        d.rectangle([x0, y0, x0+cell-gap-1, y0+cell-gap-1], fill=color)

    img.save(os.path.join(OUT, name), optimize=True)
    return name

